// Bundles offline viewer libraries into TS modules so the readers work 100% offline.
// Runs automatically on `npm install` (postinstall).
//   pdf.js  (Apache-2.0) → src/reader/pdfjsBundle.ts
//   mammoth (BSD-2)      → src/docx/mammothBundle.ts   (Word .docx → HTML)
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const safe = (s) => s.replace(/<\/script/gi, '<\\/script');

function bundle(out, header, entries) {
  const files = entries.map(([, p]) => path.join(root, 'node_modules', p));
  if (!files.every((f) => fs.existsSync(f))) {
    console.warn('missing source, keeping existing', out);
    return;
  }
  const body = entries
    .map(([name], i) => `export const ${name} = ${JSON.stringify(safe(fs.readFileSync(files[i], 'utf8')))};\n`)
    .join('');
  fs.writeFileSync(path.join(root, out), `/* AUTO-GENERATED by scripts/build-pdfjs.js — do not edit. ${header} */\n${body}`);
  console.log('bundled →', out);
}

bundle('src/reader/pdfjsBundle.ts', 'pdf.js © Mozilla, Apache-2.0', [
  ['PDFJS_WORKER', 'pdfjs-dist/legacy/build/pdf.worker.min.js'],
  ['PDFJS_LIB', 'pdfjs-dist/legacy/build/pdf.min.js'],
]);
bundle('src/docx/mammothBundle.ts', 'mammoth.js, BSD-2-Clause', [['MAMMOTH_LIB', 'mammoth/mammoth.browser.min.js']]);

// OCR (Apache-2.0): tesseract.js worker + WASM core + Arabic & English models, fully offline
(function bundleOcr() {
  const nm = path.join(root, 'node_modules');
  const files = {
    lib: 'tesseract.js/dist/tesseract.min.js',
    worker: 'tesseract.js/dist/worker.min.js',
    core: 'tesseract.js-core/tesseract-core-simd-lstm.wasm.js',
    ara: '@tesseract.js-data/ara/4.0.0_best_int/ara.traineddata.gz',
    eng: '@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz',
  };
  const out = 'src/ocr/ocrBundle.ts';
  if (!Object.values(files).every((f) => fs.existsSync(path.join(nm, f)))) {
    console.warn('OCR sources missing, keeping existing', out);
    return;
  }
  const txt = (f) => JSON.stringify(safe(fs.readFileSync(path.join(nm, f), 'utf8')));
  const b64 = (f) => JSON.stringify(fs.readFileSync(path.join(nm, f)).toString('base64'));
  fs.mkdirSync(path.join(root, 'src/ocr'), { recursive: true });
  fs.writeFileSync(
    path.join(root, out),
    '/* AUTO-GENERATED by scripts/build-pdfjs.js — do not edit. tesseract.js + models, Apache-2.0 */\n' +
      `export const TESS_LIB = ${txt(files.lib)};\n` +
      `export const TESS_WORKER = ${txt(files.worker)};\n` +
      `export const TESS_CORE = ${txt(files.core)};\n` +
      `export const TESS_ARA = ${b64(files.ara)};\n` +
      `export const TESS_ENG = ${b64(files.eng)};\n`,
  );
  console.log('bundled →', out);
})();
