// Bundles pdf.js (legacy UMD build) into a TS module so the reader works 100% offline.
// Runs automatically on `npm install` (postinstall). Output: src/reader/pdfjsBundle.ts
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'node_modules', 'pdfjs-dist', 'legacy', 'build');
const out = path.join(__dirname, '..', 'src', 'reader', 'pdfjsBundle.ts');
if (!fs.existsSync(dir)) {
  console.warn('pdfjs-dist not installed; keeping existing', out);
  process.exit(0);
}
const safe = (s) => s.replace(/<\/script/gi, '<\\/script');
const worker = safe(fs.readFileSync(path.join(dir, 'pdf.worker.min.js'), 'utf8'));
const lib = safe(fs.readFileSync(path.join(dir, 'pdf.min.js'), 'utf8'));
fs.writeFileSync(
  out,
  '/* AUTO-GENERATED by scripts/build-pdfjs.js — do not edit. pdf.js © Mozilla, Apache-2.0 */\n' +
    `export const PDFJS_WORKER = ${JSON.stringify(worker)};\n` +
    `export const PDFJS_LIB = ${JSON.stringify(lib)};\n`,
);
console.log('pdf.js bundled →', path.relative(process.cwd(), out));
